export type TranslationKey = keyof typeof english
export type Translator = (key: TranslationKey, values?: Record<string, string | number>) => string

export const TRANSLATION_KEYS = Object.keys(english) as TranslationKey[]
export const TRANSLATIONS: Record<Locale, Record<TranslationKey, string>> = {
  en: english,
  vi: vietnamese,
}

export const createTranslator = (locale: Locale): Translator => (key, values = {}) => {
  const dictionary = TRANSLATIONS[locale] ?? TRANSLATIONS.en
  const template = dictionary[key] ?? english[key]
  return Object.entries(values).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), template)
}

